import { test } from "node:test";
import assert from "node:assert/strict";
import { createAdminShortcut } from "../src/lib/shortcut.mjs";
test("shortcut requires simultaneous Z X C and triggers once until released", () => {
  const s = createAdminShortcut();
  assert.equal(s.down("z"), false);
  s.up("z");
  assert.equal(s.down("x"), false);
  s.up("x");
  assert.equal(s.down("c"), false);
  s.up("c");
  assert.equal(s.down("Z"), false);
  assert.equal(s.down("x"), false);
  assert.equal(s.down("c"), true);
  assert.equal(s.down("c"), false);
  s.up("c");
  assert.equal(s.down("c"), false);
  s.up("z");
  s.up("x");
  s.up("c");
  s.down("z");
  s.down("x");
  assert.equal(s.down("c"), true);
});
test("shortcut ignores editing fields and clears held keys on blur", () => {
  const s = createAdminShortcut();
  s.down("z", true);
  s.down("x", true);
  assert.equal(s.down("c", true), false);
  s.down("z");
  s.down("x");
  s.reset();
  assert.equal(s.down("c"), false);
});
